@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun LibraryDetailScreen(api: MediaToolsApi, itemType: String, itemId: String, onBack: () -> Unit) {
    var detail by remember(itemType, itemId) { mutableStateOf<LibraryDetail?>(null) }
    var error by remember(itemType, itemId) { mutableStateOf<String?>(null) }
    var reportTarget by remember { mutableStateOf<AIReportTarget?>(null) }

    LaunchedEffect(itemType, itemId) {
        runCatching { api.loadDetail(itemType, itemId) }
            .onSuccess { detail = it }
            .onFailure { error = it.message ?: "Could not load this item." }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(detail?.item?.title ?: "Library item", maxLines = 1) },
                navigationIcon = {
                    IconButton(onClick = onBack) { Icon(Icons.AutoMirrored.Outlined.ArrowBack, contentDescription = "Back") }
                },
            )
        },
    ) { padding ->
        when {
            error != null -> Column(Modifier.fillMaxSize().padding(padding).padding(24.dp)) {
                Text("Could not open this item", style = MaterialTheme.typography.titleLarge)
                Text(error.orEmpty(), Modifier.padding(top = 8.dp), color = MaterialTheme.colorScheme.error)
                Button(onClick = onBack, modifier = Modifier.padding(top = 16.dp)) { Text("Back to library") }
            }
            detail == null -> Column(Modifier.fillMaxSize().padding(padding).padding(24.dp)) {
                CircularProgressIndicator()
            }
            else -> SelectionContainer {
                Column(
                    Modifier.fillMaxSize().padding(padding).verticalScroll(rememberScrollState()).padding(20.dp),
                    verticalArrangement = Arrangement.spacedBy(16.dp),
                ) {
                    val loaded = requireNotNull(detail)
                    if (loaded.summary.isNotBlank()) {
                        Column(
                            Modifier.fillMaxWidth(),
                            verticalArrangement = Arrangement.spacedBy(10.dp),
                        ) {
                            Text("AI summary", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
                            Text(
                                "Generated by AI. Check important details against the source.",
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                style = MaterialTheme.typography.bodySmall,
                            )
                            Text(
                                loaded.summary,
                                modifier = Modifier.fillMaxWidth().padding(16.dp),
                                style = MaterialTheme.typography.bodyLarge,
                            )
                            loaded.summaryReportTarget?.let { target ->
                                TextButton(onClick = { reportTarget = target }) {
                                    Icon(Icons.Outlined.Flag, contentDescription = null)
                                    Text("Report this AI summary", Modifier.padding(start = 8.dp))
                                }
                            }
                        }
                    }
                    Text("Source text", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
                    Text(
                        loaded.body.ifBlank { "Text is not available yet." },
                        modifier = Modifier.fillMaxWidth().padding(16.dp),
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }
        }
    }

    reportTarget?.let { target ->
        AIReportDialog(api = api, target = target, onDismiss = { reportTarget = null })
    }
}

@Composable
private fun AIReportDialog(api: MediaToolsApi, target: AIReportTarget, onDismiss: () -> Unit) {
    val scope = rememberCoroutineScope()
    val categories = listOf(
        "dangerous" to "Dangerous or illegal",
        "hate_or_harassment" to "Hate or harassment",
        "sexual" to "Sexual content",
        "privacy" to "Privacy concern",
        "deceptive" to "Deceptive or inaccurate",
        "other" to "Something else",
    )
    var categoryIndex by remember { mutableIntStateOf(0) }
    var details by remember { mutableStateOf("") }
    var submitting by remember { mutableStateOf(false) }
    var successMessage by remember { mutableStateOf<String?>(null) }
    var submitError by remember { mutableStateOf<String?>(null) }

    AlertDialog(
        onDismissRequest = { if (!submitting) onDismiss() },
        title = { Text(if (successMessage == null) "Report AI summary" else "Report received") },
        text = {
            if (successMessage != null) {
                Text(successMessage.orEmpty())
            } else {
                Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                    Text("Choose the best reason. Media Tools attaches the selected AI output, not another copy of the source media.")
                    categories.forEachIndexed { index, (_, label) ->
                        Row(Modifier.fillMaxWidth()) {
                            androidx.compose.material3.RadioButton(
                                selected = categoryIndex == index,
                                onClick = { categoryIndex = index },
                            )
                            TextButton(onClick = { categoryIndex = index }) { Text(label) }
                        }
                    }
                    OutlinedTextField(
                        value = details,
                        onValueChange = { details = it.take(1000) },
                        label = { Text("Optional details") },
                        supportingText = { Text("${details.length}/1000") },
                        modifier = Modifier.fillMaxWidth(),
                    )
                    submitError?.let { Text(it, color = MaterialTheme.colorScheme.error) }
                }
            }
        },
        confirmButton = {
            if (successMessage != null) {
                TextButton(onClick = onDismiss) { Text("Done") }
            } else {
                Button(
                    enabled = !submitting,
                    onClick = {
                        submitting = true
                        submitError = null
                        scope.launch {
                            runCatching {
                                api.reportAIOutput(target, categories[categoryIndex].first, details)
                            }.onSuccess { receipt ->
                                successMessage = if (receipt.alreadyReported) {
                                    "You already reported this output. It remains in the review queue."
                                } else {
                                    "Thanks. This output is now in the review queue."
                                }
                            }.onFailure { submitError = it.message ?: "The report could not be sent." }
                            submitting = false
                        }
                    },
                ) { Text(if (submitting) "Sending…" else "Send report") }
            }
        },
        dismissButton = {
            if (successMessage == null) TextButton(enabled = !submitting, onClick = onDismiss) { Text("Cancel") }
        },
    )
}
